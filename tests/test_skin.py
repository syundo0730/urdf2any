"""Skinned DAE -> MuJoCo skin conversion.

The fixture is a synthetic two-bone skin (plus an unweighted third bone) whose
rest pose matches a two-link URDF, small enough that every baked vertex, UV and
weight below is hand-derived from the numbers in ``_dae_xml``. The parity anchor
is ``test_skn_is_readable_by_mujoco``: the .skn files are read back by MuJoCo's
own loader as part of a model generated by the MJCF backend.
"""

from __future__ import annotations

import dataclasses
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

import numpy as np
import pytest

from urdf2any import (
    ConvertConfig,
    convert_robot,
    load_skinned_meshes,
    mjcf_body_names,
    parse_urdf,
)
from urdf2any.backends.mjcf_skin import write_mjcf_skins
from urdf2any.skin import BIND_POSE_TOLERANCE

pytest.importorskip("collada")

BONE_LINKS = {"BoneA": "base_link", "BoneB": "upper_link"}

# Bind-pose world coordinates of the five source vertices, derived by hand:
# every vertex is shifted +0.5 in Y by the bind shape matrix; BoneB's rest pose
# (z=1) is 0.5 above its inverse bind matrix (z=0.5), so vertices weighted to it
# move up by 0.5; the center vertex is the 50/50 average of both bones.
V0 = (0.0, 0.5, 0.0)
V1 = (1.0, 0.5, 0.0)
V2 = (1.0, 0.5, 1.5)
V3 = (0.0, 0.5, 1.5)
V4 = (0.5, 0.5, 0.75)

URDF = """<?xml version="1.0"?>
<robot name="skin_robot">
  <link name="base_link">
    <inertial>
      <mass value="1.0"/>
      <inertia ixx="0.01" ixy="0" ixz="0" iyy="0.01" iyz="0" izz="0.01"/>
    </inertial>
    <collision><geometry><box size="0.2 0.2 0.2"/></geometry></collision>
  </link>
  <link name="upper_link">
    <inertial>
      <mass value="0.5"/>
      <inertia ixx="0.01" ixy="0" ixz="0" iyy="0.01" iyz="0" izz="0.01"/>
    </inertial>
    <collision><geometry><box size="0.1 0.1 0.1"/></geometry></collision>
  </link>
  <joint name="lift" type="revolute">
    <parent link="base_link"/>
    <child link="upper_link"/>
    <origin xyz="0 0 1" rpy="0 0 0"/>
    <axis xyz="0 1 0"/>
    <limit lower="-1" upper="1" effort="10" velocity="1"/>
  </joint>
</robot>
"""


# SI Z-up coordinates of the source vertices; the fixture converts them (and
# every translation) into the document's declared unit and up axis, so any
# unit/up_axis combination must bake to the same world-space result.
_SOURCE_POINTS = [(0, 0, 0), (1, 0, 0), (1, 0, 1), (0, 0, 1), (0.5, 0, 0.5)]


def _dae_xml(
    *,
    bone_b_z: float = 1.0,
    bone_c_weight: float = 0.0,
    textured: bool = True,
    unit: float = 1.0,
    up_axis: str = "Z_UP",
    texture_path: str = "skin_tex.png",
    duplicate_controller: bool = False,
) -> str:
    """A minimal skinned Collada: one quad fan, three bones, one material.

    ``bone_b_z`` moves BoneB's rest pose away from the URDF's zero pose (to
    provoke a bind-pose mismatch); ``bone_c_weight`` gives the deliberately
    unmapped BoneC a non-zero weight; ``unit``/``up_axis`` re-express the same
    scene in a different document convention; ``duplicate_controller`` adds a
    second controller whose id decodes to the same mesh name.
    """

    def pt(x: float, y: float, z: float) -> tuple[float, float, float]:
        # SI Z-up -> document coordinates (inverse of the loader's conversion).
        x, y, z = x / unit, y / unit, z / unit
        return (x, z, -y) if up_axis == "Y_UP" else (x, y, z)

    def matrix(x: float = 0.0, y: float = 0.0, z: float = 0.0) -> str:
        """Row-major 4x4 translation matrix, Collada's <matrix> layout."""
        dx, dy, dz = pt(x, y, z)
        return f"1 0 0 {dx:g} 0 1 0 {dy:g} 0 0 1 {dz:g} 0 0 0 1"

    positions = "  ".join(" ".join(f"{c:g}" for c in pt(*p)) for p in _SOURCE_POINTS)
    if textured:
        surface = """
        <newparam sid="tex-surface">
          <surface type="2D"><init_from>tex-img</init_from></surface>
        </newparam>
        <newparam sid="tex-sampler">
          <sampler2D><source>tex-surface</source></sampler2D>
        </newparam>"""
        diffuse = '<diffuse><texture texture="tex-sampler" texcoord="UVMap"/></diffuse>'
    else:
        surface = ""
        diffuse = "<diffuse><color>0.25 0.5 0.75 1</color></diffuse>"

    def controller(cid: str) -> str:
        return f"""
    <controller id="{cid}" name="Armature">
      <skin source="#Shell-mesh">
        <bind_shape_matrix>{matrix(y=0.5)}</bind_shape_matrix>
        <source id="{cid}-joints">
          <Name_array id="{cid}-joints-array" count="3">BoneA BoneB BoneC</Name_array>
          <technique_common>
            <accessor source="#{cid}-joints-array" count="3" stride="1">
              <param name="JOINT" type="name"/>
            </accessor>
          </technique_common>
        </source>
        <source id="{cid}-bind_poses">
          <float_array id="{cid}-bind_poses-array" count="48">
            {matrix()} {matrix(z=-0.5)} {matrix(x=-0.3)}
          </float_array>
          <technique_common>
            <accessor source="#{cid}-bind_poses-array" count="3" stride="16">
              <param name="TRANSFORM" type="float4x4"/>
            </accessor>
          </technique_common>
        </source>
        <source id="{cid}-weights">
          <float_array id="{cid}-weights-array" count="3">1 0.5 {bone_c_weight}</float_array>
          <technique_common>
            <accessor source="#{cid}-weights-array" count="3" stride="1">
              <param name="WEIGHT" type="float"/>
            </accessor>
          </technique_common>
        </source>
        <joints>
          <input semantic="JOINT" source="#{cid}-joints"/>
          <input semantic="INV_BIND_MATRIX" source="#{cid}-bind_poses"/>
        </joints>
        <vertex_weights count="5">
          <input semantic="JOINT" source="#{cid}-joints" offset="0"/>
          <input semantic="WEIGHT" source="#{cid}-weights" offset="1"/>
          <vcount>2 1 1 1 2</vcount>
          <v>0 0 2 2  0 0  1 0  1 0  0 1 1 1</v>
        </vertex_weights>
      </skin>
    </controller>"""

    controllers = controller("Armature_Shell-skin")
    if duplicate_controller:
        controllers += controller("Shell-skin")  # decodes to the same name "Shell"

    return f"""<?xml version="1.0" encoding="utf-8"?>
<COLLADA xmlns="http://www.collada.org/2005/11/COLLADASchema" version="1.4.1">
  <asset><unit meter="{unit:g}" name="unit"/><up_axis>{up_axis}</up_axis></asset>
  <library_images>
    <image id="tex-img" name="tex"><init_from>{texture_path}</init_from></image>
  </library_images>
  <library_effects>
    <effect id="ShellFX">
      <profile_COMMON>{surface}
        <technique sid="common"><lambert>{diffuse}</lambert></technique>
      </profile_COMMON>
    </effect>
  </library_effects>
  <library_materials>
    <material id="ShellMat" name="ShellMat"><instance_effect url="#ShellFX"/></material>
  </library_materials>
  <library_geometries>
    <geometry id="Shell-mesh" name="Shell">
      <mesh>
        <source id="Shell-positions">
          <float_array id="Shell-positions-array" count="15">
            {positions}
          </float_array>
          <technique_common>
            <accessor source="#Shell-positions-array" count="5" stride="3">
              <param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/>
            </accessor>
          </technique_common>
        </source>
        <source id="Shell-map-0">
          <float_array id="Shell-map-0-array" count="14">
            0 0  1 0  1 1  0 1  0.5 0.5  0.5 0.5  0.25 0.25
          </float_array>
          <technique_common>
            <accessor source="#Shell-map-0-array" count="7" stride="2">
              <param name="S" type="float"/><param name="T" type="float"/>
            </accessor>
          </technique_common>
        </source>
        <vertices id="Shell-vertices">
          <input semantic="POSITION" source="#Shell-positions"/>
        </vertices>
        <triangles material="ShellSymbol" count="4">
          <input semantic="VERTEX" source="#Shell-vertices" offset="0"/>
          <input semantic="TEXCOORD" source="#Shell-map-0" offset="1" set="0"/>
          <p>0 0 1 1 4 4  1 1 2 2 4 5  2 2 3 3 4 4  3 3 0 6 4 5</p>
        </triangles>
      </mesh>
    </geometry>
  </library_geometries>
  <library_controllers>{controllers}
  </library_controllers>
  <library_visual_scenes>
    <visual_scene id="Scene" name="Scene">
      <node id="Armature" name="Armature" type="NODE">
        <matrix sid="transform">{matrix()}</matrix>
        <node id="BoneA" name="BoneA" sid="BoneA" type="JOINT">
          <matrix sid="transform">{matrix()}</matrix>
          <node id="BoneB" name="BoneB" sid="BoneB" type="JOINT">
            <matrix sid="transform">{matrix(z=bone_b_z)}</matrix>
          </node>
          <node id="BoneC" name="BoneC" sid="BoneC" type="JOINT">
            <matrix sid="transform">{matrix(x=0.3)}</matrix>
          </node>
        </node>
        <instance_controller url="#Armature_Shell-skin">
          <skeleton>#BoneA</skeleton>
          <bind_material>
            <technique_common>
              <instance_material symbol="ShellSymbol" target="#ShellMat">
                <bind_vertex_input semantic="UVMap" input_semantic="TEXCOORD" input_set="0"/>
              </instance_material>
            </technique_common>
          </bind_material>
        </instance_controller>
      </node>
    </visual_scene>
  </library_visual_scenes>
  <scene><instance_visual_scene url="#Scene"/></scene>
</COLLADA>
"""


def _write_png(path: Path) -> None:
    """A 2x2 red PNG, so MuJoCo has a real image to load."""

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    raw = b"".join(b"\x00" + b"\xff\x00\x00" * 2 for _ in range(2))
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", 2, 2, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw))
        + chunk(b"IEND", b"")
    )


@pytest.fixture
def skin_scene(tmp_path):
    """(parsed robot, dae writer) sharing one directory, as a real asset tree would."""
    urdf = tmp_path / "robot.urdf"
    urdf.write_text(URDF, encoding="utf-8")
    _write_png(tmp_path / "skin_tex.png")

    def write_dae(**kwargs) -> Path:
        dae = tmp_path / "shell.dae"
        dae.write_text(_dae_xml(**kwargs), encoding="utf-8")
        return dae

    return parse_urdf(urdf), write_dae


def _load(skin_scene, **kwargs):
    robot, write_dae = skin_scene
    return load_skinned_meshes(write_dae(**kwargs), robot, BONE_LINKS)


# ----- baking ---------------------------------------------------------------


def test_vertices_are_baked_into_the_bind_pose(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    # Order follows first use by the face corners: v0, v1, v4, v2, v3, then the
    # UV-split copy of v0.
    assert np.allclose(mesh.vertices, [V0, V1, V4, V2, V3, V0])
    assert np.array_equal(mesh.faces, [[0, 1, 2], [1, 3, 2], [3, 4, 2], [4, 5, 2]])


def test_bind_poses_come_from_zero_pose_fk(skin_scene):
    model = _load(skin_scene)
    assert np.allclose(model.bind_poses["base_link"].translation, [0, 0, 0])
    assert np.allclose(model.bind_poses["upper_link"].translation, [0, 0, 1])
    assert np.allclose(model.bind_poses["upper_link"].rotation, [1, 0, 0, 0])


def test_uv_is_flipped_vertically(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    assert np.allclose(
        mesh.uv, [(0, 1), (1, 1), (0.5, 0.5), (1, 0), (0, 0), (0.25, 0.75)]
    )


def test_vertices_sharing_a_uv_value_are_merged(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    # The center vertex is referenced by two different UV *indices* holding the
    # same value: keying on the index would split it into four (one per face).
    assert len(mesh.vertices) == 6
    assert sum(1 for v in mesh.vertices if np.allclose(v, V4)) == 1
    # A genuinely different UV value does split its vertex (v0 appears twice).
    assert sum(1 for v in mesh.vertices if np.allclose(v, V0)) == 2


def test_weights_are_normalized_and_keyed_by_link(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    assert mesh.weights == {
        "base_link": {0: 1.0, 1: 1.0, 2: 0.5, 5: 1.0},
        "upper_link": {2: 0.5, 3: 1.0, 4: 1.0},
    }
    assert mesh.bone_links() == ["base_link", "upper_link"]


def test_zero_weight_bone_need_not_be_mapped(skin_scene):
    # BoneC is in the skeleton and in the weight arrays, but only with weight 0.
    (mesh,) = _load(skin_scene).meshes
    assert set(mesh.weights) == {"base_link", "upper_link"}


def test_material_texture_is_resolved(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    assert mesh.texture is not None and mesh.texture.name == "skin_tex.png"
    assert mesh.color is None


def test_flat_color_material_becomes_rgba(skin_scene):
    (mesh,) = _load(skin_scene, textured=False).meshes
    assert mesh.texture is None
    assert np.allclose(mesh.color, [0.25, 0.5, 0.75, 1.0])


def test_mesh_name_drops_the_exporter_decoration(skin_scene):
    (mesh,) = _load(skin_scene).meshes
    assert mesh.name == "Shell"


def test_unit_and_up_axis_metadata_are_normalized(skin_scene):
    # The identical scene authored in millimeters, Y-up must bake to the same
    # SI Z-up result (and still pass the bind-pose check against the FK).
    (mesh,) = _load(skin_scene, unit=0.001, up_axis="Y_UP").meshes
    assert np.allclose(mesh.vertices, [V0, V1, V4, V2, V3, V0])


def test_texture_in_a_subdirectory_is_resolved(skin_scene):
    robot, write_dae = skin_scene
    dae = write_dae(texture_path="textures/skin_tex.png")
    tex_dir = dae.parent / "textures"
    tex_dir.mkdir()
    # Move (not copy) the image so basename fallback cannot mask a bad lookup.
    (dae.parent / "skin_tex.png").rename(tex_dir / "skin_tex.png")
    (mesh,) = load_skinned_meshes(dae, robot, BONE_LINKS).meshes
    assert mesh.texture == tex_dir / "skin_tex.png"


# ----- validation -----------------------------------------------------------


def test_bind_pose_mismatch_raises(skin_scene):
    with pytest.raises(ValueError, match="bind pose mismatch for bone 'BoneB'"):
        _load(skin_scene, bone_b_z=1.0 + 10 * BIND_POSE_TOLERANCE)


def test_bind_pose_within_tolerance_is_accepted(skin_scene):
    _load(skin_scene, bone_b_z=1.0 + 0.5 * BIND_POSE_TOLERANCE)


def test_weighted_bone_without_mapping_raises(skin_scene):
    with pytest.raises(ValueError, match="BoneC.*not in the bone -> link mapping"):
        _load(skin_scene, bone_c_weight=0.25)


def test_negative_weight_raises(skin_scene):
    # A negative weight would corrupt the baked positions and normalization
    # rather than fail; reject it at decode time.
    with pytest.raises(ValueError, match="invalid skinning weight"):
        _load(skin_scene, bone_c_weight=-0.25)


def test_mapping_to_unknown_link_raises(skin_scene):
    robot, write_dae = skin_scene
    with pytest.raises(ValueError, match="not in the robot"):
        load_skinned_meshes(write_dae(), robot, {"BoneA": "base_link", "BoneB": "missing_link"})


def test_duplicate_mesh_names_raise(skin_scene):
    # "Armature_Shell-skin" and "Shell-skin" both decode to "Shell"; failing
    # beats one .skn silently overwriting the other.
    with pytest.raises(ValueError, match="duplicate skinned mesh name 'Shell'"):
        _load(skin_scene, duplicate_controller=True)


